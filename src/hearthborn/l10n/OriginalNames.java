package hearthborn.l10n;

import haven.*;

/**
 * Recover names assembled by game sprites from already translated resource tooltips.
 *
 * @author Jagy2014
 */
public final class OriginalNames {
    private static final String STACK = ", stack of";

    private OriginalNames() {}

    public static String item(ItemInfo.Owner owner, String source) {
        if(!(owner instanceof ItemInfo.ResOwner)) return source;
        Resource resource = ((ItemInfo.ResOwner)owner).resource();
        String suffix = source.endsWith(STACK) ? STACK : "";
        String name = source.substring(0, source.length() - suffix.length());
        Resource.Tooltip base = resource.layer(Resource.tooltip);
        if(base != null && name.equals(base.t)) return base.original + suffix;
        if(!(owner instanceof GItem) || !resource.name.equals("gfx/invobjs/meat")) return source;
        GItem item = (GItem)owner;
        if(item.sdt == null || item.sdt.eom()) return source;
        try {
            Resource.Resolver resolver = owner.context(Resource.Resolver.class);
            if(resolver == null) return source;
            Message data = item.sdt.clone();
            String english = null, shown = null;
            while(!data.eom()) {
                Resource.Tooltip part = resolver.getres(data.uint16()).get().layer(Resource.tooltip);
                if(part == null) continue;
                english = combine(english, part.original);
                shown = combine(shown, part.t);
            }
            english = finish(english);
            shown = finish(shown);
            // Preserve custom names and decorations that were not generated by this sprite.
            if(english != null && (name.equals(shown) || name.equals(english))) return english + suffix;
        } catch(OwnerContext.NoContext | Message.EOF unavailable) {
            // A missing resolver or a changed sprite format leaves the supplied name intact.
        }
        return source;
    }

    /** Match the game's meat sprite composition, including the order of its template layers. */
    private static String combine(String first, String next) {
        if(first == null) return next;
        int at = first.indexOf('%');
        if(at < 0) return next.indexOf('%') >= 0 ? combine(next, first) : first;
        return first.substring(0, at) + next + first.substring(at + 1);
    }

    private static String finish(String name) {
        if(name == null) return null;
        int at = name.indexOf('%');
        return at < 0 ? name : name.substring(0, at).trim() + " " + name.substring(at + 1).trim();
    }
}
